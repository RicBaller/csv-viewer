const LANG_STORAGE_KEY = 'csv-viewer-lang';

let lang = 'en';

function readSavedLanguage() {
  try {
    return localStorage.getItem(LANG_STORAGE_KEY);
  } catch {
    return null;
  }
}

// Saved choice first, then the browser's preferred languages (exact tag, then base language), then English.
function detectLanguage() {
  const saved = readSavedLanguage();
  if (saved && TRANSLATIONS[saved]) return saved;
  const preferred = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language];
  for (const tag of preferred) {
    if (!tag) continue;
    const lower = tag.toLowerCase();
    if (TRANSLATIONS[lower]) return lower;
    const base = lower.split('-')[0];
    if (TRANSLATIONS[base]) return base;
  }
  return 'en';
}

function t(key, params = {}) {
  let msg = TRANSLATIONS[lang][key] ?? TRANSLATIONS.en[key] ?? key;
  if (typeof msg === 'object') {
    msg = msg[new Intl.PluralRules(lang).select(params.n)] ?? msg.other;
  }
  return msg.replace(/\{(\w+)\}/g, (m, name) => (name in params ? params[name] : m));
}

// Fills every element marked with data-i18n (text) or data-i18n-aria-label.
function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
}

function setLanguage(code, { save = false } = {}) {
  lang = TRANSLATIONS[code] ? code : 'en';
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGUAGES.includes(lang) ? 'rtl' : 'ltr';
  if (save) {
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
      // Storage blocked: choice lasts for this page load only.
    }
  }
  applyTranslations();
}
